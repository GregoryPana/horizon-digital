import sharp from 'sharp';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const captures=JSON.parse(await readFile(path.join(root,'docs/assets/portfolio-devices/captures.json'),'utf8'));
if(captures.length!==10 || captures.some(c=>c.error)) throw new Error('Require 10 real successful device captures');
const out=path.join(root,'src/assets/work/device-renders');await mkdir(out,{recursive:true});
const imports=[];const entries=[];
for(const id of ['drake','horizon-auto','takamaka','forma','beauty']){
 const devices=[];
 for(const device of ['desktop','mobile']){
  const capture=captures.find(c=>c.id===id&&c.device===device);
  const input=path.join(root,'docs/assets/portfolio-devices',capture.file);
  const width=device==='desktop'?1200:390;
  const name=`${id}-${device}`;const identifier=name.replace(/-([a-z])/g,(_,c)=>c.toUpperCase());
  const result=await sharp(input).resize({width,withoutEnlargement:true}).webp({quality:86}).toFile(path.join(out,name+'.webp'));
  imports.push(`import ${identifier} from "../assets/work/device-renders/${name}.webp";`);
  const sources=[];
  for(const variantWidth of device==='desktop'?[640,960]:[260]){
   const variantId=identifier+variantWidth;
   await sharp(input).resize({width:variantWidth,withoutEnlargement:true}).webp({quality:86}).toFile(path.join(out,`${name}-${variantWidth}.webp`));
   imports.push(`import ${variantId} from "../assets/work/device-renders/${name}-${variantWidth}.webp";`);
   sources.push(`\${${variantId}} ${variantWidth}w`);
  }
  sources.push(`\${${identifier}} ${result.width}w`);
  devices.push(`${device}: { src: ${identifier}, srcSet: \`${sources.join(', ')}\`, width: ${result.width}, height: ${result.height}, viewportWidth: ${capture.geometry.width}, viewportHeight: ${capture.geometry.height} }`);
 }
 entries.push(`  "${id}": { ${devices.join(', ')} }`);
}
await writeFile(path.join(root,'src/data/portfolioDeviceMedia.ts'),'// Generated by scripts/generate-portfolio-device-images.mjs from actual device captures.\n'+imports.join('\n')+'\n\nexport const portfolioDeviceMedia = {\n'+entries.join(',\n')+'\n} as const;\n');
console.log('Generated 10 source renders, 15 responsive derivatives and typed manifest');
