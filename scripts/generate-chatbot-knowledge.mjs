import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const factsPath = path.join(root, "src/data/businessFacts.json");
const knowledgeDir = path.join(root, "knowledge");
const facts = JSON.parse(await readFile(factsPath, "utf8"));
const checkOnly = process.argv.includes("--check");
const generatedHeader = `<!-- Generated from src/data/businessFacts.json by scripts/generate-chatbot-knowledge.mjs. Do not edit this file directly. -->\n\n`;
const absoluteUrl = (pathname) => new URL(pathname, `${facts.site.url}/`).toString();
const bullet = (items) => items.map((item) => `- ${item}`).join("\n");

const contact = `${generatedHeader}# Contact Horizon Digital

- **WhatsApp and phone:** ${facts.site.phone}
- **Email:** ${facts.site.email}
- **Contact page:** ${absoluteUrl(facts.site.contactPath)}
- **Based in:** ${facts.site.location}
- **Service area:** ${facts.site.serviceArea}

Horizon Digital aims to reply ${facts.site.responseTime}. WhatsApp is the quickest direct contact option shown on the website.

## What to share

${bullet([
  "Your business name and industry",
  "What you need the website to help with",
  "Your current website, if you have one",
  "Your preferred timeline",
  "The package tier that interests you, or whether you need guidance",
])}

The first conversation is free and does not commit you to a project.
`;

const services = `${generatedHeader}# Horizon Digital services

${facts.business.description}

## Website capabilities

${facts.business.services.map((service) => `### ${service.title}\n\n${service.description}`).join("\n\n")}

## Complete service catalogue

${facts.serviceCatalogue.map((service) => `### ${service.title}\n\n- **Pathway:** ${service.pathway}\n- **Type:** ${service.serviceType}\n\n${service.description}${service.accessRequirement ? `\n\n${service.accessRequirement}` : ""}`).join("\n\n")}

## Existing-website support flow

${facts.existingWebsiteFlow.map((step, index) => `### ${index + 1}. ${step.title}\n\n${step.description}`).join("\n\n")}

## Scope boundaries

${facts.serviceScopeBoundaries.map((boundary) => `### ${boundary.title}\n\n${boundary.description}`).join("\n\n")}

Package tiers and inclusions are published at ${absoluteUrl(facts.site.pricingPath)}. Exact quotes are confirmed after a free consultation.
`;

const pricing = `${generatedHeader}# Website packages and pricing

Foundation, Starter and Growth are tiered by scope. Custom work is scoped separately. The written proposal, prepared after a free consultation, confirms the final scope, price, responsibilities and exclusions.

${facts.packages.map((pkg) => `## ${pkg.title}\n\n${pkg.description}\n\n${pkg.includes.map((item) => `- **${item.title}:** ${item.description}`).join("\n")}`).join("\n\n")}

## Payment terms

${bullet(facts.paymentTerms)}

## Optional add-ons

${facts.addOns.map((item) => `- ${item.title}`).join("\n")}

Search rankings, traffic, enquiries, bookings and revenue are not guaranteed.
`;

const faq = `${generatedHeader}# Common questions

${facts.faqs.map((item) => `## ${item.question}\n\n${item.answer}`).join("\n\n")}
`;

const processContent = `${generatedHeader}# Project process

${facts.projectSteps.map((step, index) => `## ${index + 1}. ${step.title}\n\n${step.description}`).join("\n\n")}

## Typical timing

Many standard projects take around 3 to 6 weeks. The estimate depends on scope, content readiness, feedback and integrations, and is confirmed in the proposal.
`;

const hosting = `${generatedHeader}# ${facts.hosting.title}

**${facts.hosting.billing}**

${facts.hosting.details.join("\n\n")}

## Included

${bullet(facts.hosting.features)}

${facts.hosting.note}
`;

const about = `${generatedHeader}# About Horizon Digital

${facts.business.description}

${facts.business.positioning}

## Working approach

- Direct communication with the person responsible for the build
- Tiered packages with exact quotes confirmed after a free consultation
- A written project scope before implementation
- Responsive design and technical SEO foundations
- Post-launch support based on the selected package

Horizon Digital does not guarantee PageSpeed scores, search positions, traffic, enquiries, bookings or revenue.

View the website at ${facts.site.url}.
`;

const work = `${generatedHeader}# Selected work and concepts

Portfolio labels must distinguish live client work from concepts and demonstration sites.

${facts.portfolio.map((project) => `## ${project.title}\n\n- **Status:** ${project.status}\n- **Description:** ${project.outcome}\n- **URL:** ${absoluteUrl(project.url)}`).join("\n\n")}

Do not describe a concept or demonstration as client work. Do not claim business outcomes unless Horizon Digital has evidence and permission to publish them.
`;

const outputs = {
  "contact.md": contact,
  "services.md": services,
  "pricing.md": pricing,
  "faq.md": faq,
  "process.md": processContent,
  "hosting.md": hosting,
  "about.md": about,
  "work.md": work,
};

await mkdir(knowledgeDir, { recursive: true });
const stale = [];
for (const [filename, content] of Object.entries(outputs)) {
  const target = path.join(knowledgeDir, filename);
  if (checkOnly) {
    let current = "";
    try {
      current = await readFile(target, "utf8");
    } catch {}
    if (current !== content) stale.push(filename);
  } else {
    await writeFile(target, content, "utf8");
    console.log(`generated ${path.relative(root, target)}`);
  }
}

if (checkOnly && stale.length) {
  console.error(`Chatbot knowledge is stale: ${stale.join(", ")}`);
  console.error("Run: npm run knowledge:generate");
  process.exit(1);
}

if (checkOnly) console.log(`Chatbot knowledge check passed (${Object.keys(outputs).length} files).`);
